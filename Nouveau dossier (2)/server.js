app.post('/api/register', rateLimit({ windowMs: 15 * 60 * 1000, max: 5, key: req => `register:${req.ip}` }), async (req, res, next) => {
  try {
    const name = cleanText(req.body.name, 100), email = normalizeEmail(req.body.email), password = String(req.body.password || '');
    if (name.length < 2) return res.status(400).json({ error: 'Le nom doit contenir au moins 2 caractères.' });
    if (!validEmail(email)) return res.status(400).json({ error: 'Adresse e-mail invalide.' });
    if (password.length < 8 || password.length > 200) return res.status(400).json({ error: 'Le mot de passe doit contenir au moins 8 caractères.' });
    if (await one('SELECT id FROM users WHERE email = $1', [email])) return res.status(409).json({ error: 'Cette adresse e-mail est déjà utilisée.' });
    const hash = await bcrypt.hash(password, 12);
    const r = await q('INSERT INTO users (name, email, password_hash) VALUES ($1, $2, $3) RETURNING id', [name, email, hash]);
    req.session.userId = Number(r.rows[0].id);
    res.status(201).json({ message: 'Compte créé avec succès.', user: await getUserById(req.session.userId) });
  } catch (e) { if (e.code === '23505') return res.status(409).json({ error: 'Cette adresse e-mail est déjà utilisée.' }); next(e); }
});

