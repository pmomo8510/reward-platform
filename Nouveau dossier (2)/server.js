app.post('/api/admin/withdrawals/:id', requireAdmin, rateLimit({ windowMs: 60 * 1000, max: 30, key: req => `admin-withdrawal:${req.session.userId}` }), async (req, res, next) => {
  const client = await pool.connect();
  try {
    const withdrawalId = Number(req.params.id), status = String(req.body.status || '').trim(), paymentReference = cleanText(req.body.paymentReference, 120);
    if (!Number.isInteger(withdrawalId)) return res.status(400).json({ error: 'Demande de retrait invalide.' });
    if (!['approved', 'rejected'].includes(status)) return res.status(400).json({ error: 'Statut invalide.' });
    if (status === 'approved' && !paymentReference) return res.status(400).json({ error: 'Renseignez la référence du paiement manuel (transaction, reçu, etc.).' });
    await client.query('BEGIN');
    const w = (await client.query('SELECT id, user_id, amount, status FROM withdrawals WHERE id = $1 FOR UPDATE', [withdrawalId])).rows[0];
    if (!w) throw new Error('NOT_FOUND');
    if (w.status !== 'pending') throw new Error('NOT_PENDING');
    if (status === 'rejected') await client.query('UPDATE users SET balance = balance + $1 WHERE id = $2', [w.amount, w.user_id]);
    const r = status === 'approved'
      ? await client.query("UPDATE withdrawals SET status = $1, payment_reference = $2, paid_at = CURRENT_TIMESTAMP, paid_by = $3 WHERE id = $4 AND status = 'pending'", [status, paymentReference, req.session.userId, withdrawalId])
      : await client.query("UPDATE withdrawals SET status = $1 WHERE id = $2 AND status = 'pending'", [status, withdrawalId]);
    if (r.rowCount !== 1) throw new Error('NOT_PENDING');
    await client.query('COMMIT');
    res.json({ message: status === 'approved' ? 'Paiement manuel confirmé et retrait marqué comme payé.' : 'Retrait refusé et montant recrédité.' });
  } catch (e) { try { await client.query('ROLLBACK'); } catch {} if (e.message === 'NOT_FOUND') return res.status(404).json({ error: 'Demande de retrait introuvable.' }); if (e.message === 'NOT_PENDING') return res.status(409).json({ error: 'Cette demande a déjà été traitée.' }); next(e); } finally { client.release(); }
});

