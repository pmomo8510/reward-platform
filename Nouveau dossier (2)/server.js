async function initDb() {
  await q(`
    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      balance BIGINT NOT NULL DEFAULT 0,
      is_admin INTEGER NOT NULL DEFAULT 0,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      payment_reference TEXT,
      paid_at TIMESTAMPTZ,
      paid_by BIGINT
    );
    CREATE TABLE IF NOT EXISTS ads (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title TEXT NOT NULL,
      duration INTEGER NOT NULL DEFAULT 10,
      reward BIGINT NOT NULL DEFAULT 500,
      active INTEGER NOT NULL DEFAULT 1,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      payment_reference TEXT,
      paid_at TIMESTAMPTZ,
      paid_by BIGINT
    );
    CREATE TABLE IF NOT EXISTS ad_views (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      ad_id BIGINT NOT NULL REFERENCES ads(id) ON DELETE CASCADE,
      reward BIGINT NOT NULL,
      viewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS ad_sessions (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      ad_id BIGINT NOT NULL REFERENCES ads(id) ON DELETE CASCADE,
      started_at BIGINT NOT NULL,
      completed INTEGER NOT NULL DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS withdrawals (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      amount BIGINT NOT NULL,
      method TEXT NOT NULL,
      account TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      payment_reference TEXT,
      paid_at TIMESTAMPTZ,
      paid_by BIGINT
    );
    CREATE INDEX IF NOT EXISTS idx_ad_sessions_user_ad ON ad_sessions(user_id, ad_id, completed);
    CREATE INDEX IF NOT EXISTS idx_ad_views_user ON ad_views(user_id);
    CREATE INDEX IF NOT EXISTS idx_withdrawals_user ON withdrawals(user_id);
    CREATE INDEX IF NOT EXISTS idx_withdrawals_status ON withdrawals(status);
  `);

  const ad = await one('SELECT id FROM ads LIMIT 1');
  if (!ad) {
    await q('INSERT INTO ads (title, duration, reward, active) VALUES ($1, $2, $3, 1)', ['Publicité sponsorisée', 10, AD_REWARD]);
  }
  await q('UPDATE ads SET reward = $1', [AD_REWARD]);
}

async function bootstrapAdmin() {
  const adminEmail = normalizeEmail(process.env.ADMIN_EMAIL);
  const adminPassword = String(process.env.ADMIN_PASSWORD || '');
  if (!adminEmail && !adminPassword) return;
  if (!validEmail(adminEmail) || adminPassword.length < 12) throw new Error('ADMIN_EMAIL doit être valide et ADMIN_PASSWORD doit contenir au moins 12 caractères.');
  const existing = await one('SELECT id FROM users WHERE is_admin = 1 LIMIT 1');
  if (!existing) {
    const hash = await bcrypt.hash(adminPassword, 12);
    await q('INSERT INTO users (name, email, password_hash, is_admin) VALUES ($1, $2, $3, 1)', ['Administrateur', adminEmail, hash]);
    console.log('Compte administrateur initial créé.');
  }
}

function cleanText(value, max = 200) { return String(value ?? '').trim().slice(0, max); }
function normalizeEmail(value) { return String(value ?? '').trim().toLowerCase().slice(0, 254); }
function validEmail(value) { return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value); }

const rateBuckets = new Map();
function rateLimit({ windowMs, max, key = req => `${req.ip}:${req.path}` }) {
  return (req, res, next) => {
    const now = Date.now();
    const bucketKey = key(req);
    let bucket = rateBuckets.get(bucketKey);
    if (!bucket || bucket.resetAt <= now) { bucket = { count: 0, resetAt: now + windowMs }; rateBuckets.set(bucketKey, bucket); }
    bucket.count += 1;
    if (bucket.count > max) return res.status(429).json({ error: 'Trop de requêtes. Réessayez plus tard.' });
    next();
  };
}
setInterval(() => { const now = Date.now(); for (const [k, b] of rateBuckets) if (b.resetAt <= now) rateBuckets.delete(k); }, 15 * 60 * 1000).unref();

