app.post('/api/ads/:id/view', requireAuth, rateLimit({ windowMs: 60 * 1000, max: 20, key: req => `ad-view:${req.session.userId}` }), async (req, res, next) => {
  const client = await pool.connect();
  try {
    const userId = req.session.userId, adId = Number(req.params.id), sessionId = Number(req.body.sessionId);
    if (!Number.isInteger(adId)) return res.status(400).json({ error: 'Publicité invalide.' });
    if (!Number.isInteger(sessionId)) return res.status(400).json({ error: 'Session de visionnage invalide.' });
    const ad = await one('SELECT id, title, duration, reward FROM ads WHERE id = $1 AND active = 1', [adId]);
    if (!ad) return res.status(404).json({ error: 'Publicité introuvable.' });
    const viewing = await one('SELECT id, started_at, completed FROM ad_sessions WHERE id = $1 AND user_id = $2 AND ad_id = $3', [sessionId, userId, adId]);
    if (!viewing) return res.status(403).json({ error: 'Session de visionnage introuvable.' });
    if (viewing.completed) return res.status(409).json({ error: 'Cette session a déjà été utilisée.' });
    const elapsed = Date.now() - Number(viewing.started_at), required = Number(ad.duration) * 1000;
    if (elapsed < required) return res.status(400).json({ error: `Visionnage trop court. Encore ${Math.ceil((required - elapsed) / 1000)} seconde(s).` });
    if (elapsed > (Number(ad.duration) + 60) * 1000) { await q('UPDATE ad_sessions SET completed = 1 WHERE id = $1 AND completed = 0', [sessionId]); return res.status(400).json({ error: 'Cette session de visionnage a expiré.' }); }
    await client.query('BEGIN');
    const changed = await client.query('UPDATE ad_sessions SET completed = 1 WHERE id = $1 AND completed = 0', [sessionId]);
    if (changed.rowCount !== 1) throw new Error('ALREADY_COMPLETED');
    await client.query('INSERT INTO ad_views (user_id, ad_id, reward) VALUES ($1, $2, $3)', [userId, ad.id, ad.reward]);
    await client.query('UPDATE users SET balance = balance + $1 WHERE id = $2', [ad.reward, userId]);
    await client.query('COMMIT');
    const user = await getUserById(userId);
    res.json({ message: 'Publicité validée et récompense de 500 F CFA ajoutée.', reward: Number(ad.reward), balance: Number(user.balance) });
  } catch (e) { try { await client.query('ROLLBACK'); } catch {} if (e.message === 'ALREADY_COMPLETED') return res.status(409).json({ error: 'Cette session a déjà été utilisée.' }); next(e); } finally { client.release(); }
});

