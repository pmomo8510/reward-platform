async function adminData() {
  const users = await all('SELECT id, name, email, balance, created_at FROM users ORDER BY id DESC');
  const withdrawals = await all(`SELECT w.id, w.amount, w.method, w.account, w.status, w.created_at, w.payment_reference, w.paid_at, w.paid_by, u.name AS user_name, u.email AS user_email FROM withdrawals w JOIN users u ON u.id = w.user_id ORDER BY w.id DESC`);
  const userCount = Number((await one('SELECT COUNT(*)::int AS count FROM users')).count);
  const totalBalance = Number((await one('SELECT COALESCE(SUM(balance),0)::bigint AS total FROM users')).total);
  const withdrawalCount = Number((await one('SELECT COUNT(*)::int AS count FROM withdrawals')).count);
  return { stats: { userCount, totalBalance, withdrawalCount }, users, withdrawals };
}
