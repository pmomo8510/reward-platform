app.post('/api/withdraw', requireAuth, rateLimit({ windowMs: 60 * 60 * 1000, max: 5, key: req => `withdraw:${req.session.userId}` }), async (req, res, next) => {
  const client = await pool.connect();
  try {
    const userId = req.session.userId, amount = Number(req.body.amount), method = cleanText(req.body.method, 50), account = cleanText(req.body.account, 200);
    if (!Number.isInteger(amount) || amount <= 0) return res.status(400).json({ error: 'Montant invalide.' });
    if (amount < MIN_WITHDRAWAL) return res.status(400).json({ error: `Le retrait minimum est de ${MIN_WITHDRAWAL.toLocaleString('fr-FR')} F CFA.` });
    if (!new Set(['TMoney', 'Flooz', 'PayPal', 'USDT', 'Autre']).has(method)) return res.status(400).json({ error: 'Moyen de paiement invalide.' });
    if (!account) return res.status(400).json({ error: 'Veuillez renseigner votre compte de paiement.' });
    await client.query('BEGIN');
    const result = await client.query('UPDATE users SET balance = balance - $1 WHERE id = $2 AND balance >= $1', [amount, userId]);
    if (result.rowCount !== 1) throw new Error('INSUFFICIENT_BALANCE');
    const r = await client.query('INSERT INTO withdrawals (user_id, amount, method, account) VALUES ($1, $2, $3, $4) RETURNING id', [userId, amount, method, account]);
    await client.query('COMMIT');
    const updated = await getUserById(userId);
    res.json({ message: 'Demande de retrait enregistrée.', withdrawalId: Number(r.rows[0].id), balance: Number(updated.balance) });
  } catch (e) { try { await client.query('ROLLBACK'); } catch {} if (e.message === 'INSUFFICIENT_BALANCE') return res.status(400).json({ error: 'Solde insuffisant pour effectuer ce retrait.' }); next(e); } finally { client.release(); }
});

